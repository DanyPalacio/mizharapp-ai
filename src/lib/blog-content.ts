// Generate full blog articles list
export function generateBlogArticles(): BlogArticle[] {
  const allArticles: BlogArticle[] = [];
  const categories = Object.entries(BLOG_ARTICLES_OUTLINE);

  categories.forEach(([categoryKey, articles]) => {
    articles.forEach((article, index) => {
      allArticles.push({
        id: `blog_${categoryKey}_${index + 1}`,
        title: article.title,
        slug: article.slug,
        excerpt: article.excerpt,
        category: article.category as any,
        author: 'MIZHAR Team',
        published_date: new Date(Date.now() - Math.random() * 30 * 24 * 60 * 60 * 1000).toISOString(),
        keywords: article.keywords,
        reading_time: article.reading_time,
        status: 'published',
        tags: [article.category, ...article.keywords.slice(0, 2)],
      });
    });
  });

  return allArticles;
}

